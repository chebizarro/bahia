func supportsManagedRuntimeConfig(runtimeType domain.RuntimeType) bool {
	switch runtimeType {
	case domain.RuntimeTypeDocker, domain.RuntimeTypeCompose:
		return true
	default:
		return false
	}
}

func (h *EncryptedRouteHandlers) authorizeServiceUpdate(ctx context.Context, authorizer encryptedTenantAuthorizer, event *nostr.Event, payload dto.UpdateServiceRequest) (*domain.Service, error) {
	if payload.ID == uuid.Nil {
		return nil, fmt.Errorf("service_id is required")
	}
	if h.services == nil {
		return nil, fmt.Errorf("service repository is not configured")
	}
	svc, err := h.services.GetByID(ctx, payload.ID)
	if err != nil {
		if err == repository.ErrNotFound {
			return nil, fmt.Errorf("service not found")
		}
		return nil, fmt.Errorf("failed to fetch service")
	}
	if svc == nil {
		return nil, fmt.Errorf("service not found")
	}
	if svc.OrgID != uuid.Nil {
		if err := authorizer.authorizeOrg(ctx, event, svc.OrgID, domain.PermWriteServices); err != nil {
			return nil, err
		}
		return svc, nil
	}
	if payload.OrgID == nil || *payload.OrgID == uuid.Nil {
		return nil, fmt.Errorf("organization is required")
	}
	if err := authorizer.authorizeOrg(ctx, event, *payload.OrgID, domain.PermWriteServices); err != nil {
		return nil, err
	}
	return svc, nil
}

func (h *EncryptedRouteHandlers) CreateService(ctx context.Context, request ContextVMRequest) (any, error) {
	if h.registry == nil {
		return nil, fmt.Errorf("service registry mutation handling is not configured")
	}
	var payload dto.CreateServiceRequest
	if err := decodeStrictContextVMParams(request.RPC.Params, &payload); err != nil {
		return nil, err
	}
	name := strings.TrimSpace(payload.Name)
	artifactRepo := strings.TrimSpace(payload.ArtifactRepo)
	if name == "" || artifactRepo == "" {
		return nil, fmt.Errorf("name and artifact_repo are required")
	}
	serviceID, _, err := domain.ResolveCreateEntityID(payload.ID)
	if err != nil {
		return nil, fmt.Errorf("invalid id: %w", err)
	}
	authorizer := encryptedTenantAuthorizer{services: h.services, environments: h.registry, rbac: h.rbac}
	if err := authorizer.authorizeOrg(ctx, request.Event, payload.OrgID, domain.PermWriteServices); err != nil {
		return nil, err
	}
	runtimeType := domain.RuntimeTypeDocker
	if strings.TrimSpace(payload.RuntimeType) != "" {
		runtimeType = domain.RuntimeType(strings.TrimSpace(payload.RuntimeType))
		if err := domain.ValidateRuntimeType(runtimeType); err != nil {
			return nil, fmt.Errorf("invalid runtime_type: %w", err)
		}
	}
	defaultBranch := strings.TrimSpace(payload.DefaultBranch)
	if defaultBranch == "" {
		defaultBranch = "main"
	}
	repositoryRef := repositoryRefFromRequest(payload.Repository)
	repoURL := strings.TrimSpace(payload.RepoURL)
	if repositoryRef != nil && strings.TrimSpace(repositoryRef.CloneURL) != "" {
		repoURL = strings.TrimSpace(repositoryRef.CloneURL)
	}
	svc := &domain.Service{
		ID:            serviceID,
		OrgID:         payload.OrgID,
		Name:          name,
		RepoURL:       repoURL,
		Repository:    repositoryRef,
		ArtifactRepo:  artifactRepo,
		DefaultBranch: defaultBranch,
		RuntimeType:   runtimeType,
	}
	if payload.ManagedRuntimeConfig != nil {
		if !supportsManagedRuntimeConfig(svc.RuntimeType) {
			return nil, fmt.Errorf("managed runtime configuration requires a managed runtime_type")
		}
		managed := domain.NormalizeManagedRuntimeConfig(payload.ManagedRuntimeConfig)
		if err := domain.ValidateManagedRuntimeConfig(managed); err != nil {
			return nil, fmt.Errorf("invalid managed runtime configuration: %w", err)
		}
		if len(managed.SecretRefs) > 0 && h.secrets == nil {
			return nil, fmt.Errorf("secret repository is required to validate managed secret references")
		}
		for _, ref := range managed.SecretRefs {
			secret, err := h.secrets.GetByID(ctx, ref.SecretID)
			if err != nil || secret == nil || secret.ServiceID != svc.ID {
				return nil, fmt.Errorf("managed runtime configuration contains an unavailable secret reference")
			}
		}
		svc.RuntimeConfig = &domain.ServiceRuntimeConfig{Managed: managed}
	}
	// Phase 3 dual dispatch (§4.1): when the service domain is enabled,
	// route through ProcessInProcess for shared idempotency with relay intents.
	if h.serviceIntentEnabled() {
		intent := h.serviceIntentFromContextVM(request, "create", svc, effectiveIdempotencyKey(request, payload.IdempotencyKey))
		if err := h.intentProcessor.ProcessInProcess(ctx, intent); err != nil {
			return nil, fmt.Errorf("failed to create service: %w", err)
		}
		// Read back the service to return the stamped entity.
		created, _ := h.services.GetByID(ctx, svc.ID)
		if created != nil {
			svc = created
		}
	} else if err := h.registry.CreateService(ctx, svc); err != nil {
		return nil, fmt.Errorf("failed to create service: %w", err)
	}
	return map[string]any{"status": "created", "service": svc, "service_id": svc.ID.String(), "idempotency_key": effectiveIdempotencyKey(request, payload.IdempotencyKey)}, nil
}

func (h *EncryptedRouteHandlers) UpdateService(ctx context.Context, request ContextVMRequest) (any, error) {
	if h.registry == nil {
		return nil, fmt.Errorf("service registry mutation handling is not configured")
	}
	var payload dto.UpdateServiceRequest
	if err := decodeStrictContextVMParams(request.RPC.Params, &payload); err != nil {
		return nil, err
	}
	authorizer := encryptedTenantAuthorizer{services: h.services, environments: h.registry, rbac: h.rbac}
	svc, err := h.authorizeServiceUpdate(ctx, authorizer, request.Event, payload)
	if err != nil {
		return nil, err
	}
	if payload.OrgID != nil {
		if *payload.OrgID == uuid.Nil {
			return nil, fmt.Errorf("org_id must not be nil")
		}
		if svc.OrgID != uuid.Nil && svc.OrgID != *payload.OrgID {
			return nil, fmt.Errorf("cannot move service to a different organization")
		}
		svc.OrgID = *payload.OrgID
	}
	if payload.Name != nil {
		name := strings.TrimSpace(*payload.Name)
		if name == "" {
			return nil, fmt.Errorf("name must not be empty")
		}
		svc.Name = name
	}
	if payload.RepoURL != nil {
		svc.RepoURL = strings.TrimSpace(*payload.RepoURL)
		if svc.Repository != nil {
			svc.Repository.CloneURL = svc.RepoURL
		}
	}
	if payload.Repository != nil {
		svc.Repository = repositoryRefFromRequest(payload.Repository)
		if svc.Repository != nil && strings.TrimSpace(svc.Repository.CloneURL) != "" {
			svc.RepoURL = strings.TrimSpace(svc.Repository.CloneURL)
		}
	}
	if payload.ArtifactRepo != nil {
		artifactRepo := strings.TrimSpace(*payload.ArtifactRepo)
		if artifactRepo == "" {
			return nil, fmt.Errorf("artifact_repo must not be empty")
		}
		svc.ArtifactRepo = artifactRepo
	}
	if payload.DefaultBranch != nil {
		branch := strings.TrimSpace(*payload.DefaultBranch)
		if branch == "" {
			return nil, fmt.Errorf("default_branch must not be empty")
		}
		svc.DefaultBranch = branch
	}
	if payload.RuntimeType != nil {
		runtimeType := domain.RuntimeType(strings.TrimSpace(*payload.RuntimeType))
		if err := domain.ValidateRuntimeType(runtimeType); err != nil {
			return nil, fmt.Errorf("invalid runtime_type: %w", err)
		}
		svc.RuntimeType = runtimeType
	}
	if !supportsManagedRuntimeConfig(svc.RuntimeType) && svc.RuntimeConfig != nil && svc.RuntimeConfig.Managed != nil && payload.ManagedRuntimeConfig == nil {
		return nil, fmt.Errorf("cannot change a service with managed runtime configuration to an unmanaged runtime_type")
	}
	if payload.ManagedRuntimeConfig != nil {
		if !supportsManagedRuntimeConfig(svc.RuntimeType) {
			return nil, fmt.Errorf("managed runtime configuration requires a managed runtime_type")
		}
		managed := domain.NormalizeManagedRuntimeConfig(payload.ManagedRuntimeConfig)
		if err := domain.ValidateManagedRuntimeConfig(managed); err != nil {
			return nil, fmt.Errorf("invalid managed runtime configuration: %w", err)
		}
		if len(managed.SecretRefs) > 0 && h.secrets == nil {
			return nil, fmt.Errorf("secret repository is required to validate managed secret references")
		}
		for _, ref := range managed.SecretRefs {
			secret, err := h.secrets.GetByID(ctx, ref.SecretID)
			if err != nil || secret == nil || secret.ServiceID != svc.ID {
				return nil, fmt.Errorf("managed runtime configuration contains an unavailable secret reference")
			}
		}
		if svc.RuntimeConfig == nil {
			svc.RuntimeConfig = &domain.ServiceRuntimeConfig{}
		}
		svc.RuntimeConfig.Managed = managed
	}
	if payload.AdoptedPublicEnvironment != nil {
		if svc.RuntimeConfig == nil || svc.RuntimeConfig.Adopted == nil {
			return nil, fmt.Errorf("adopted_public_environment requires an already-adopted service")
		}
		if svc.RuntimeConfig.Adopted.Environment == nil {
			svc.RuntimeConfig.Adopted.Environment = map[string]string{}
		}
		for key, value := range payload.AdoptedPublicEnvironment {
			key = strings.TrimSpace(key)
			if !strings.HasPrefix(key, "PUBLIC_") {
				return nil, fmt.Errorf("adopted public environment key %q must use the PUBLIC_ prefix", key)
			}
			svc.RuntimeConfig.Adopted.Environment[key] = value
		}
	}
	// Phase 3 dual dispatch (§4.1): when the service domain is enabled,
	// route through ProcessInProcess for shared idempotency with relay intents.
	if h.serviceIntentEnabled() {
		intent := h.serviceIntentFromContextVM(request, "update", svc, effectiveIdempotencyKey(request, payload.IdempotencyKey))
		if payload.ExpectedUpdatedAt != nil && !payload.ExpectedUpdatedAt.IsZero() {
			ts := payload.ExpectedUpdatedAt.Format(time.RFC3339Nano)
			intent.Content["expected_updated_at"] = ts
			epoch := payload.ExpectedUpdatedAt.UnixNano()
			intent.ExpectedUpdatedAt = &epoch
		}
		if err := h.intentProcessor.ProcessInProcess(ctx, intent); err != nil {
			return nil, fmt.Errorf("failed to update service: %w", err)
		}
		updated, _ := h.services.GetByID(ctx, svc.ID)
		if updated != nil {
			svc = updated
		}
	} else if payload.ExpectedUpdatedAt != nil && !payload.ExpectedUpdatedAt.IsZero() {
		if err := h.registry.UpdateServiceWithExpectedRevision(ctx, svc, *payload.ExpectedUpdatedAt); err != nil {
			return nil, fmt.Errorf("failed to update service: %w", err)
		}
	} else if err := h.registry.UpdateService(ctx, svc); err != nil {
		return nil, fmt.Errorf("failed to update service: %w", err)
	}
	return map[string]any{"status": "updated", "service": svc, "service_id": svc.ID.String(), "idempotency_key": effectiveIdempotencyKey(request, payload.IdempotencyKey)}, nil
}

func (h *EncryptedRouteHandlers) DeleteService(ctx context.Context, request ContextVMRequest) (any, error) {
	if h.registry == nil {
		return nil, fmt.Errorf("service registry mutation handling is not configured")
	}
	var payload dto.DeleteServiceRequest
	if err := decodeStrictContextVMParams(request.RPC.Params, &payload); err != nil {
		return nil, err
	}
	authorizer := encryptedTenantAuthorizer{services: h.services, environments: h.registry, rbac: h.rbac}
	if _, err := authorizer.authorizeService(ctx, request.Event, payload.ID, domain.PermWriteServices); err != nil {
		return nil, err
	}
	// Phase 3 dual dispatch (§4.1): when the service domain is enabled,
	// route through ProcessInProcess for shared idempotency with relay intents.
	if h.serviceIntentEnabled() {
		intent := h.serviceIntentFromContextVM(request, "delete", &domain.Service{ID: payload.ID}, effectiveIdempotencyKey(request, payload.IdempotencyKey))
		intent.Content["deleted"] = true
		intent.Content["force"] = payload.Force
		if err := h.intentProcessor.ProcessInProcess(ctx, intent); err != nil {
			return nil, fmt.Errorf("failed to delete service: %w", err)
		}
	} else if err := h.registry.DeleteService(ctx, payload.ID, payload.Force); err != nil {
		return nil, fmt.Errorf("failed to delete service: %w", err)
	}
	return map[string]any{"status": "deleted", "service_id": payload.ID.String(), "idempotency_key": effectiveIdempotencyKey(request, payload.IdempotencyKey)}, nil
}

// serviceIntentFromContextVM builds a synthetic Intent for the dual-dispatch
// path (§4.1). The ContextVM handler has already authorized the request; the
// intent processor shares the same idempotency store as the relay path.
func (h *EncryptedRouteHandlers) serviceIntentFromContextVM(request ContextVMRequest, op string, svc *domain.Service, idempotencyKey string) *Intent {
	content := map[string]interface{}{
		"id":             svc.ID.String(),
		"name":           svc.Name,
		"repo_url":       svc.RepoURL,
		"artifact_repo":  svc.ArtifactRepo,
		"default_branch": svc.DefaultBranch,
		"runtime_type":   string(svc.RuntimeType),
		"org_id":         svc.OrgID.String(),
	}
	if svc.Repository != nil {
		content["repository"] = svc.Repository
	}

	intentID := idempotencyKey
	if intentID == "" {
		intentID = domain.NewEntityID().String()
	}

	actor := ""
	if request.Event != nil {
		actor = request.Event.PubKey.Hex()
	}

	return &Intent{
		Domain:     "service",
		Op:         op,
		OrgID:      svc.OrgID,
		IntentID:   intentID,
		Coordinate: svc.ID.String(),
		Content:    content,
		Actor:      actor,
	}
}

