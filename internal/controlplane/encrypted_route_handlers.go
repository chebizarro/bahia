// NewEncryptedRouteHandlers adapts sensitive route-only actions onto encrypted
// signer-first encrypted request/result operations. Secrets, stored run logs, and
// signature verification results are never projected to the public sidecar.
func NewEncryptedRouteHandlers(cfg EncryptedRouteHandlersConfig) *EncryptedRouteHandlers {
	logger := cfg.Logger
	if logger == nil {
		logger = zap.NewNop()
	}
	return &EncryptedRouteHandlers{
		intentProcessor: cfg.IntentProcessor,
		secrets:         cfg.Secrets,
		encryptor:       cfg.Encryptor,
		secretPublisher: cfg.SecretPublisher,
		notifRepo:       cfg.NotifRepo,
		notifPublisher:  cfg.NotifPublisher,
		notifNotifier:   cfg.NotifNotifier,
		runs:            cfg.Runs,
		runLogs:         cfg.RunLogs,
		artifacts:       cfg.Artifacts,
		signatures:      cfg.Signatures,
		signVerifier:    cfg.SignVerifier,
		services:        cfg.Services,
		intents:         cfg.Intents,
		registry:        cfg.Registry,
		deploymentUnits: cfg.DeploymentUnits,
		rbac:            cfg.RBAC,
		logger:          logger.Named("encrypted-route-handlers"),
	}
}

func (h *EncryptedRouteHandlers) Register(transport *EncryptedRequestTransport) {
	if h == nil || transport == nil {
		return
	}
	h.registerRouteHandler(transport, EncryptedOperationServiceSecretsList, h.ListSecrets, ContextVMMethodServiceSecretsList)
	h.registerRouteHandler(transport, EncryptedOperationServiceSecretsCreate, h.CreateSecret, ContextVMMethodServiceSecretsCreate)
	h.registerRouteHandler(transport, EncryptedOperationServiceSecretsUpdate, h.UpdateSecret, ContextVMMethodServiceSecretsUpdate)
	h.registerRouteHandler(transport, EncryptedOperationServiceSecretsDelete, h.DeleteSecret, ContextVMMethodServiceSecretsDelete)
	h.registerRouteHandler(transport, EncryptedOperationServiceSecretsReveal, h.RevealSecret, ContextVMMethodServiceSecretsReveal)
	h.registerRouteHandler(transport, EncryptedOperationDeploymentRunLogsGet, h.GetRunLogs, ContextVMMethodDeploymentRunLogsGet)
	h.registerRouteHandler(transport, EncryptedOperationArtifactSignaturesVerify, h.VerifyArtifactSignatures)
	transport.RegisterContextVMHandler(ContextVMMethodServiceCreate, h.CreateService)
	transport.RegisterContextVMHandler(ContextVMMethodServiceUpdate, h.UpdateService)
	transport.RegisterContextVMHandler(ContextVMMethodServiceDelete, h.DeleteService)
	transport.RegisterContextVMHandler(ContextVMMethodEnvironmentCreate, h.CreateEnvironment)
	transport.RegisterContextVMHandler(ContextVMMethodEnvironmentGetDetails, h.GetEnvironmentDetails)
	transport.RegisterContextVMHandler(ContextVMMethodEnvironmentUpdate, h.UpdateEnvironment)
	transport.RegisterContextVMHandler(ContextVMMethodEnvironmentDelete, h.DeleteEnvironment)
	transport.RegisterContextVMHandler(ContextVMMethodArtifactRegister, h.RegisterArtifact)
	transport.RegisterContextVMHandler(ContextVMMethodArtifactImportObserved, h.ImportObservedArtifact)
	h.registerContextVMRouteHandler(transport, EncryptedOperationNotificationChannelsCreate, h.CreateNotificationChannel, ContextVMMethodNotificationChannelCreate, ContextVMMethodNotificationChannelsCreate)
	h.registerContextVMRouteHandler(transport, EncryptedOperationNotificationChannelsUpdate, h.UpdateNotificationChannel, ContextVMMethodNotificationChannelUpdate, ContextVMMethodNotificationChannelsUpdate)
	h.registerContextVMRouteHandler(transport, EncryptedOperationNotificationChannelsDelete, h.DeleteNotificationChannel, ContextVMMethodNotificationChannelDelete, ContextVMMethodNotificationChannelsDelete)
}

// ImportObservedArtifact records an already-running, observation-verified image
// as governed build/artifact lineage so an operator never needs to edit the
// database to bridge missing artifact state. It deliberately leaves desired
// state alone: aligning it stays a separate, reviewed deployment.
func (h *EncryptedRouteHandlers) ImportObservedArtifact(ctx context.Context, request ContextVMRequest) (any, error) {
	if h.registry == nil {
		return nil, fmt.Errorf("artifact registry mutation handling is not configured")
	}
	var payload dto.ImportObservedArtifactRequest
	if err := decodeStrictContextVMParams(request.RPC.Params, &payload); err != nil {
		return nil, err
	}
	if payload.ServiceID == uuid.Nil || payload.EnvironmentID == uuid.Nil {
		return nil, fmt.Errorf("service_id and environment_id are required")
	}
	if payload.DeploymentUnitID != nil && *payload.DeploymentUnitID == uuid.Nil {
		return nil, fmt.Errorf("deployment_unit_id must not be nil")
	}
	authorizer := encryptedTenantAuthorizer{services: h.services, environments: h.registry, rbac: h.rbac}
	// Authorize the environment too: the payload names one, and every other
	// service+environment mutation proves the operator owns both.
	if _, _, err := authorizer.authorizeServiceEnvironment(
		ctx, request.Event, payload.ServiceID, payload.EnvironmentID,
		domain.PermWriteServices, domain.PermWriteServices,
	); err != nil {
		return nil, err
	}
	requestedBy := ""
	if request.Event != nil {
		requestedBy = strings.TrimSpace(request.Event.PubKey.Hex())
	}
	result, err := h.registry.ImportObservedArtifact(ctx, service.ImportObservedArtifactInput{
		ServiceID:        payload.ServiceID,
		EnvironmentID:    payload.EnvironmentID,
		DeploymentUnitID: payload.DeploymentUnitID,
		ImageRepo:        strings.TrimSpace(payload.ImageRepo),
		ImageTag:         strings.TrimSpace(payload.ImageTag),
		ImageDigest:      strings.TrimSpace(payload.ImageDigest),
		GitSHA:           strings.TrimSpace(payload.GitSHA),
		GitRef:           strings.TrimSpace(payload.GitRef),
		RequestedBy:      requestedBy,
	})
	if err != nil {
		return nil, err
	}
	response := map[string]any{
		"status":            result.Status,
		"artifact":          result.Artifact,
		"observed_digest":   result.ObservedDigest,
		"observation_id":    result.ObservationID.String(),
		"registry_verified": result.RegistryVerified,
		"verified_labels":   result.VerifiedLabels,
		"desired_state":     result.DesiredStateNote,
		"idempotency_key":   effectiveIdempotencyKey(request, payload.IdempotencyKey),
	}
	if result.Artifact != nil {
		response["artifact_id"] = result.Artifact.ID.String()
	}
	if result.Build != nil {
		response["build"] = result.Build
		response["build_id"] = result.Build.ID.String()
	}
	return response, nil
}

func (h *EncryptedRouteHandlers) RegisterArtifact(ctx context.Context, request ContextVMRequest) (any, error) {
	if h.registry == nil {
		return nil, fmt.Errorf("artifact registry mutation handling is not configured")
	}
	var payload dto.RegisterArtifactRequest
	if err := decodeStrictContextVMParams(request.RPC.Params, &payload); err != nil {
		return nil, err
	}
	if payload.BuildID == uuid.Nil || payload.ServiceID == uuid.Nil {
		return nil, fmt.Errorf("build_id and service_id are required")
	}
	if strings.TrimSpace(payload.ImageRepo) == "" || strings.TrimSpace(payload.ImageTag) == "" || strings.TrimSpace(payload.ImageDigest) == "" {
		return nil, fmt.Errorf("image_repo, image_tag, and image_digest are required")
	}
	authorizer := encryptedTenantAuthorizer{services: h.services, environments: h.registry, rbac: h.rbac}
	if _, err := authorizer.authorizeService(ctx, request.Event, payload.ServiceID, domain.PermWriteServices); err != nil {
		return nil, err
	}
	scanStatus := domain.ScanStatus(strings.TrimSpace(payload.ScanStatus))
	if scanStatus == "" {
		scanStatus = domain.ScanStatusUnknown
	}
	artifact := &domain.Artifact{
		BuildID: payload.BuildID, ServiceID: payload.ServiceID,
		ImageRepo: strings.TrimSpace(payload.ImageRepo), ImageTag: strings.TrimSpace(payload.ImageTag),
		ImageDigest: strings.TrimSpace(payload.ImageDigest), ManifestMediaType: strings.TrimSpace(payload.ManifestMediaType),
		SizeBytes: payload.SizeBytes, SBOMURL: strings.TrimSpace(payload.SBOMURL), SignatureRef: strings.TrimSpace(payload.SignatureRef),
		ScanStatus: scanStatus, Metadata: payload.Metadata,
	}
	if err := h.registry.RegisterArtifact(ctx, artifact); err != nil {
		return nil, fmt.Errorf("failed to register artifact: %w", err)
	}
	return map[string]any{"status": "registered", "artifact": artifact, "artifact_id": artifact.ID.String()}, nil
}

type encryptedRouteHandler = EncryptedRequestHandler

func (h *EncryptedRouteHandlers) registerRouteHandler(transport *EncryptedRequestTransport, operation string, handler encryptedRouteHandler, contextVMAliases ...string) {
	transport.RegisterHandler(operation, handler)
	register := func(method string) {
		transport.RegisterContextVMHandler(method, func(ctx context.Context, request ContextVMRequest) (any, error) {
			return handler(ctx, EncryptedRequest{Event: request.Event, Envelope: EncryptedRequestEnvelope{Version: ContextVMWireVersion, Operation: operation, RequesterPubkey: request.Event.PubKey.Hex(), Payload: request.RPC.Params}})
		})
	}
	register(operation)
	for _, alias := range contextVMAliases {
		register(alias)
	}
}

// registerContextVMRouteHandler registers a ContextVMHandler under the
// encrypted operation name and all ContextVM method aliases. It mirrors
// registerRouteHandler for handlers already written against ContextVMRequest.
func (h *EncryptedRouteHandlers) registerContextVMRouteHandler(transport *EncryptedRequestTransport, operation string, handler ContextVMHandler, contextVMAliases ...string) {
	transport.RegisterHandler(operation, func(ctx context.Context, req EncryptedRequest) (any, error) {
		return handler(ctx, ContextVMRequest{
			Event: req.Event,
			RPC:   ContextVMJSONRPCRequest{Method: req.Envelope.Operation, Params: req.Envelope.Payload},
		})
	})
	transport.RegisterContextVMHandler(operation, handler)
	for _, alias := range contextVMAliases {
		transport.RegisterContextVMHandler(alias, handler)
	}
}

